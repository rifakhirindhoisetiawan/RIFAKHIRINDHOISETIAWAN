-- Tabel kegiatan Daily Task: dipakai tabel kegiatan di
-- public/daily-task/daily-task-admin.html (muncul setelah baris menu diklik)
-- dan halaman menu public/utility/{hari,minggu,bulan}.html.
-- Jalankan di Supabase Dashboard > SQL Editor > New Query > paste & Run
-- Link: https://supabase.com/dashboard/project/xsacwgxxoptdrgbbzzib/sql/new

create table if not exists daily_task_items (
  id         bigint generated by default as identity primary key,
  period     text not null,
  text       text not null,
  sort_order integer not null default 1,
  created_at timestamptz not null default now()
);

create index if not exists daily_task_items_period_idx
  on daily_task_items (period, sort_order);

alter table daily_task_items enable row level security;

drop policy if exists "Public read daily_task_items" on daily_task_items;
drop policy if exists "Allow insert daily_task_items" on daily_task_items;
drop policy if exists "Allow update daily_task_items" on daily_task_items;
drop policy if exists "Allow delete daily_task_items" on daily_task_items;

create policy "Public read daily_task_items"
  on daily_task_items for select using (true);
create policy "Allow insert daily_task_items"
  on daily_task_items for insert with check (true);
create policy "Allow update daily_task_items"
  on daily_task_items for update using (true) with check (true);
create policy "Allow delete daily_task_items"
  on daily_task_items for delete using (true);

-- Verifikasi
select period, text, sort_order from daily_task_items order by period, sort_order;