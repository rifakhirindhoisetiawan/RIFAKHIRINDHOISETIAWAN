-- 1. Tabel produk NOTE
create table if not exists note_products (
  id         bigint generated by default as identity primary key,
  plu        text not null,
  deskripsi  text not null,
  kategori   text not null default 'RTE',
  sort_order integer not null default 1,
  foto_url   text,
  created_at timestamptz not null default now()
);

create index if not exists note_products_order_idx
  on note_products (sort_order);

-- 2. RLS + policy (pola sama seperti daily_task_items)
alter table note_products enable row level security;

drop policy if exists "Public read note_products" on note_products;
drop policy if exists "Allow insert note_products" on note_products;
drop policy if exists "Allow update note_products" on note_products;
drop policy if exists "Allow delete note_products" on note_products;

create policy "Public read note_products"
  on note_products for select using (true);
create policy "Allow insert note_products"
  on note_products for insert with check (true);
create policy "Allow update note_products"
  on note_products for update using (true) with check (true);
create policy "Allow delete note_products"
  on note_products for delete using (true);

-- 3. Bucket foto NOTE (path: note/<id>.jpg)
insert into storage.buckets (id, name, public)
values ('note-foto', 'note-foto', true)
on conflict (id) do update set public = true;

drop policy if exists "Public read note-foto" on storage.objects;
drop policy if exists "Allow upload note-foto" on storage.objects;
drop policy if exists "Allow update note-foto" on storage.objects;
drop policy if exists "Allow delete note-foto" on storage.objects;

create policy "Public read note-foto"
  on storage.objects for select using (bucket_id = 'note-foto');
create policy "Allow upload note-foto"
  on storage.objects for insert with check (bucket_id = 'note-foto');
create policy "Allow update note-foto"
  on storage.objects for update using (bucket_id = 'note-foto')
  with check (bucket_id = 'note-foto');
create policy "Allow delete note-foto"
  on storage.objects for delete using (bucket_id = 'note-foto');

-- 4. Verifikasi
select id, plu, deskripsi, kategori, sort_order, foto_url
from note_products order by sort_order;